//! Developer: statistics for training the coder's default context tables (DESIGN.md §5.2).
//!
//! An [`Encoder`](crate::Encoder) asked to [`record_contexts`](crate::Encoder::record_contexts)
//! counts, per context set, how often every CDF codes every symbol. `vdwt train-contexts` turns
//! those counts into `entropy/trained.rs`.

use std::fmt::Write;

use crate::codec::{self, CLASSES};
use crate::entropy::{CDFS, MAX_SYMBOLS};

/// Context sets: the band classes, then the motion section's three planes.
pub(crate) const SETS: usize = CLASSES + 3;

/// Symbols per CDF and context set.
#[derive(Clone, Debug)]
pub struct ContextStats {
    counts: Vec<[[u64; MAX_SYMBOLS]; CDFS]>,
}

impl Default for ContextStats {
    fn default() -> Self {
        Self {
            counts: vec![[[0; MAX_SYMBOLS]; CDFS]; SETS],
        }
    }
}

impl ContextStats {
    pub(crate) fn add(&mut self, set: usize, symbols: &[(u8, u8)]) {
        for &(k, s) in symbols {
            self.counts[set][usize::from(k)][usize::from(s)] += 1;
        }
    }

    pub fn merge(&mut self, other: &ContextStats) {
        for (a, b) in self.counts.iter_mut().zip(&other.counts) {
            for (a, b) in a.iter_mut().zip(b) {
                for (a, b) in a.iter_mut().zip(b) {
                    *a += b;
                }
            }
        }
    }

    /// Symbols counted.
    pub fn symbols(&self) -> u64 {
        self.counts.iter().flatten().flatten().sum()
    }

    /// `entropy/trained.rs` for these statistics: every CDF that coded at least `min_symbols`
    /// symbols gets their frequencies (with half a count added to each, in 1/32768).
    pub fn to_rust(&self, min_symbols: u64) -> String {
        let sizes = alphabet_sizes();
        let mut out = String::from(
            "//! The coder's default context tables, trained on a disjoint corpus (DESIGN.md §5.2).\n\
             //!\n\
             //! Generated by `vdwt train-contexts`; do not edit. Per context set (the band classes of\n\
             //! `codec`, then the motion section's Δx, Δy and intra planes): the CDFs that differ from the\n\
             //! untrained defaults, as `(index in Contexts::cdfs, symbol probabilities)`.\n\n\
             pub(crate) static TRAINED: [&[(u8, &[u16])]; crate::training::SETS] = [\n",
        );
        for (set, counts) in self.counts.iter().enumerate() {
            let mut body = String::new();
            for (k, c) in counts.iter().enumerate() {
                let n = sizes[set][k];
                let total: u64 = c[..n].iter().sum();
                if total < min_symbols {
                    continue;
                }
                let probs: Vec<String> = c[..n]
                    .iter()
                    .map(|&v| {
                        let p = (2 * v + 1) as f64 / (2 * total + n as u64) as f64;
                        ((p * 32768.0).round() as u64).clamp(1, 32767).to_string()
                    })
                    .collect();
                let _ = writeln!(body, "        ({k}, &[{}]),", probs.join(", "));
            }
            if body.is_empty() {
                out.push_str("    &[],\n");
            } else {
                out.push_str("    &[\n");
                out.push_str(&body);
                out.push_str("    ],\n");
            }
        }
        out.push_str("];\n");
        out
    }
}

/// Every CDF's alphabet size, per context set.
fn alphabet_sizes() -> Vec<Vec<usize>> {
    codec::untrained_contexts()
        .iter()
        .map(|c| c.cdfs().map(|cdf| cdf.symbols()).collect())
        .collect()
}
